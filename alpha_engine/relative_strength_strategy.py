def _compute_rsi(closes: list[float], period: int = 14) -> float | None:
    """Compute RSI using Wilder's smoothing method. Pure Python."""
    if len(closes) < period + 1:
        return None

    gains = []
    losses = []
    for i in range(1, len(closes)):
        diff = closes[i] - closes[i - 1]
        gains.append(max(diff, 0.0))
        losses.append(max(-diff, 0.0))

    if len(gains) < period:
        return None

    avg_gain = sum(gains[:period]) / period
    avg_loss = sum(losses[:period]) / period

    for i in range(period, len(gains)):
        avg_gain = (avg_gain * (period - 1) + gains[i]) / period
        avg_loss = (avg_loss * (period - 1) + losses[i]) / period

    if avg_loss == 0:
        return 100.0
    rs = avg_gain / avg_loss
    return 100.0 - (100.0 / (1.0 + rs))


def _compute_sma(values: list[float], period: int) -> list[float]:
    """Compute Simple Moving Average. Returns list same length as input (NaN-padded with 0)."""
    result = []
    for i in range(len(values)):
        if i < period - 1:
            result.append(0.0)
        else:
            window = values[i - period + 1: i + 1]
            result.append(sum(window) / period)
    return result


def _compute_7d_return(closes: list[float]) -> float | None:
    """Compute 7-day return from hourly closes (168 candles)."""
    if len(closes) < 2:
        return None
    start = closes[0]
    end = closes[-1]
    if start <= 0:
        return None
    return ((end - start) / start) * 100.0


def _compute_volume_recovery_ratio(volumes: list[float]) -> float:
    """Ratio of last 12h volume to prior 12h volume.

    > 1.0 means volume is increasing (recovery signal).
    """
    if len(volumes) < 24:
        # Use whatever we have, split in half
        mid = len(volumes) // 2
        if mid == 0:
            return 0.0
        recent = volumes[mid:]
        prior = volumes[:mid]
    else:
        recent = volumes[-12:]
        prior = volumes[-24:-12]

    sum_prior = sum(prior)
    sum_recent = sum(recent)
    if sum_prior <= 0:
        return 0.0
    return sum_recent / sum_prior


def _find_sma_cross_bars_ago(closes: list[float], sma_values: list[float]) -> int | None:
    """Find how many bars ago price crossed above the SMA.

    Returns number of bars ago (0 = current bar), or None if no cross found
    in the last 24 bars. Negative means price is still below SMA.
    """
    if len(closes) < 2 or len(sma_values) < 2:
        return None

    # Search backward from most recent bar
    search_range = min(24, len(closes) - 1)
    for i in range(len(closes) - 1, len(closes) - 1 - search_range, -1):
        if i < 1 or sma_values[i] == 0 or sma_values[i - 1] == 0:
            continue
        # Cross = price was below SMA, now above
        if closes[i] >= sma_values[i] and closes[i - 1] < sma_values[i - 1]:
            return len(closes) - 1 - i

    # Check if currently above SMA (may have crossed earlier)
    if closes[-1] >= sma_values[-1] > 0:
        return -1  # Above but no recent cross found

    return None  # Below SMA, no cross


def _smart_round(value: float) -> float:
    """Round to sensible precision based on magnitude."""
    if value == 0:
        return 0.0
    abs_val = abs(value)
    if abs_val >= 100:
        return round(value, 2)
    elif abs_val >= 1:
        return round(value, 4)
    elif abs_val >= 0.01:
        return round(value, 6)
    return round(value, 10)


