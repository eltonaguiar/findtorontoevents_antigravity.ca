"""
ALPHA_ENGINE -- Relative Strength Recovery Scanner
====================================================
Standalone scanner that finds coins at maximum pessimism starting to recover.

Concept: The weakest performers over 7 days represent maximum pessimism.
When these coins show early recovery signals (RSI turning up, volume surge,
SMA cross), they offer the best mean-reversion upside.

Filter vs Scanner distinction:
- The existing `select_rel_strength()` in portfolio_manager.py is a FILTER
  that re-ranks picks already generated by other strategies.
- THIS module is a SCANNER that fetches raw market data from Binance Futures
  and generates its own picks independently.

Forward test results: 100% WR on 2 trades (small sample, promising signal).

Recovery signal criteria (ALL must be true):
1. Coin is in bottom 20% of 7-day performers (weakest of the weak)
2. RSI(14) > 30 (not still in freefall -- stabilising)
3. Volume increasing (last 12h volume > 1.3x prior 12h volume)
4. Price crossed above 20-period SMA (trend reversal confirmation)

Risk management:
- TP = entry + 6% (mean-reversion target)
- SL = entry - 2.5% (tight stop, R:R = 2.4:1)
- LONG only (recovery = upside bounce)

References:
- Jegadeesh (1990) "Evidence of Predictable Behavior of Security Returns"
- De Bondt & Thaler (1985) "Does the Stock Market Overreact?"
- Poterba & Summers (1988) mean-reversion in stock prices
"""

