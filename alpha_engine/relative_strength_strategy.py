def _fetch_futures_24h_tickers() -> list[dict] | None:
    """Fetch ALL Binance Futures 24h tickers with full failover chain.

    Returns list of dicts with: symbol, priceChangePercent, lastPrice, quoteVolume.
    Falls back to Binance Spot -> KuCoin -> CoinGecko if futures endpoints fail.
    """
    # Source 1: Binance Futures (fapi/v1/ticker/24hr)
    for base in FAPI_BASES:
        url = f"{base}/fapi/v1/ticker/24hr"
        data = _fetch_json(url, timeout=20)
        if data and isinstance(data, list) and len(data) > 10:
            log.info("  [TICKER] Binance Futures: %d tickers", len(data))
            return data
        time.sleep(_RATE_LIMIT_DELAY)

    # Source 2: Binance Spot (api/v3/ticker/24hr) as fallback
    for base in SPOT_BASES:
        url = f"{base}/api/v3/ticker/24hr"
        data = _fetch_json(url, timeout=20)
        if data and isinstance(data, list) and len(data) > 10:
            log.info("  [TICKER] Binance Spot fallback: %d tickers", len(data))
            return data
        time.sleep(_RATE_LIMIT_DELAY)

    # Source 3: KuCoin allTickers
    url = f"{KUCOIN_BASE}/api/v1/market/allTickers"
    data = _fetch_json(url, timeout=15)
    if data and isinstance(data, dict) and data.get("data", {}).get("ticker"):
        tickers = data["data"]["ticker"]
        usdt = [t for t in tickers if t.get("symbol", "").endswith("-USDT")]
        # Normalize to Binance-like format
        result = []
        for t in usdt:
            try:
                result.append({
                    "symbol": t["symbol"].replace("-", ""),
                    "priceChangePercent": str(float(t.get("changeRate", 0)) * 100),
                    "lastPrice": t.get("last", "0"),
                    "quoteVolume": t.get("volValue", "0"),
                })
            except (ValueError, KeyError):
                continue
        if result:
            log.info("  [TICKER] KuCoin fallback: %d tickers", len(result))
            return result

    # Source 4: CoinGecko markets (limited to top 250)
    all_coins = []
    for page in range(1, 3):
        url = (f"{COINGECKO_BASE}/coins/markets?vs_currency=usd"
               f"&order=market_cap_desc&per_page=250&page={page}")
        data = _fetch_json(url, timeout=15)
        if data and isinstance(data, list):
            all_coins.extend(data)
        time.sleep(_RATE_LIMIT_DELAY)

    if all_coins:
        result = []
        for c in all_coins:
            sym = c.get("symbol", "").upper()
            pcp = c.get("price_change_percentage_24h")
            if sym and pcp is not None:
                result.append({
                    "symbol": f"{sym}USDT",
                    "priceChangePercent": str(pcp),
                    "lastPrice": str(c.get("current_price", 0)),
                    "quoteVolume": str(c.get("total_volume", 0)),
                })
        if result:
            log.info("  [TICKER] CoinGecko fallback: %d tickers", len(result))
            return result

    log.warning("All ticker sources failed")
    return None


