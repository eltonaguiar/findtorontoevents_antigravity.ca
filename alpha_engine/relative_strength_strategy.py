def scan_relative_strength(symbols: list[str] | None = None) -> list[dict]:
    """Scan for relative strength recovery setups.

    1. Fetches 24h tickers for ALL USDT pairs from Binance Futures
    2. Identifies bottom 20 performers by 7-day return
    3. For each, fetches 168 1h candles (7 days)
    4. Checks recovery criteria: RSI > 30, volume surge, SMA cross
    5. Returns qualifying picks sorted by confidence (best first)

    Args:
        symbols: Optional list of symbols to scan. If None, scans the weakest
                 performers from the full Binance Futures universe.

    Returns:
        List of pick dicts in active_picks.json format.
    """
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    # -- Step 1: Get all tickers and rank by performance --
    if symbols is not None:
        # Caller provided specific symbols -- scan those directly
        bottom_symbols = symbols
        total_pairs = len(symbols)
        log.info("Scanning %d provided symbols", len(symbols))
    else:
        log.info("Fetching all USDT futures tickers...")
        tickers = _fetch_futures_24h_tickers()
        if not tickers:
            log.error("Failed to fetch tickers from any source")
            return []

        # Filter to USDT perpetual pairs, exclude leveraged tokens and stablecoins
        _EXCLUDE_SUFFIXES = ("DOWNUSDT", "UPUSDT", "BULLUSDT", "BEARUSDT")
        _STABLES = ("USDCUSDT", "BUSDUSDT", "TUSDUSDT", "DAIUSDT", "FDUSDUSDT", "USDTUSDT")

        usdt_tickers = []
        for t in tickers:
            sym = t.get("symbol", "")
            if not sym.endswith("USDT"):
                continue
            if sym in _STABLES:
                continue
            if any(sym.endswith(s) for s in _EXCLUDE_SUFFIXES):
                continue
            try:
                pcp = float(t.get("priceChangePercent", 0))
                price = float(t.get("lastPrice", 0))
                vol = float(t.get("quoteVolume", 0))
            except (ValueError, TypeError):
                continue
            if price <= 0 or vol <= 0:
                continue
            usdt_tickers.append({
                "symbol": sym,
                "price_change_pct_24h": pcp,
                "last_price": price,
                "quote_volume": vol,
            })

        total_pairs = len(usdt_tickers)
        log.info("Found %d valid USDT pairs", total_pairs)

        if total_pairs == 0:
            log.error("No valid USDT pairs found")
            return []

        # We need 7-day returns, but the 24h ticker only gives 24h change.
        # Strategy: use 24h change as initial ranking proxy, then compute
        # true 7d return from klines for the bottom candidates.
        # Sort by 24h change ascending (worst performers first)
        usdt_tickers.sort(key=lambda x: x["price_change_pct_24h"])

        # Take bottom 20 by 24h performance as candidates for 7d analysis
        bottom_count = max(20, total_pairs // 5)  # At least 20, or bottom 20%
        bottom_candidates = usdt_tickers[:bottom_count]
        bottom_symbols = [t["symbol"] for t in bottom_candidates]
        log.info("Selected %d worst 24h performers for 7d analysis", len(bottom_symbols))

    # -- Step 2: Fetch 7d klines and compute true 7d return for each --
    candidates_with_data = []
    scanned = 0
    failed = 0

    for symbol in bottom_symbols:
        time.sleep(_RATE_LIMIT_DELAY)
        candles = _fetch_klines(symbol, interval="1h", limit=168)
        if not candles or len(candles) < 50:
            failed += 1
            log.debug("Skipping %s: insufficient candle data (%d)",
                      symbol, len(candles) if candles else 0)
            continue

        scanned += 1
        closes = [c["close"] for c in candles]
        volumes = [c["volume"] for c in candles]

        # True 7-day return
        perf_7d = _compute_7d_return(closes)
        if perf_7d is None:
            continue

        candidates_with_data.append({
            "symbol": symbol,
            "candles": candles,
            "closes": closes,
            "volumes": volumes,
            "perf_7d": perf_7d,
        })

    log.info("Fetched klines: %d scanned, %d failed", scanned, failed)

    if not candidates_with_data:
        log.info("No candidates with sufficient data")
        return []

    # Re-rank by actual 7-day return and take bottom 20%
    candidates_with_data.sort(key=lambda x: x["perf_7d"])
    cutoff = max(1, len(candidates_with_data) // 5)  # Bottom 20%
    bottom_20pct = candidates_with_data[:max(cutoff, 1)]

    log.info("Bottom 20%% by 7d return: %d coins (cutoff: %.2f%%)",
             len(bottom_20pct),
             bottom_20pct[-1]["perf_7d"] if bottom_20pct else 0)

    # -- Step 3: Apply recovery signal filters --
    # Load existing picks for dedup
    existing_ids = set()
    if ACTIVE_PICKS_PATH.exists():
        try:
            active = json.loads(ACTIVE_PICKS_PATH.read_text(encoding="utf-8"))
            existing_ids = {p.get("id", "") for p in active}
        except Exception:
            pass

    picks = []

    for cand in bottom_20pct:
        symbol = cand["symbol"]
        closes = cand["closes"]
        volumes = cand["volumes"]
        perf_7d = cand["perf_7d"]
        current_price = closes[-1]

        # Rank: position among ALL candidates (1 = worst performer)
        rank_7d = next(
            (i + 1 for i, c in enumerate(candidates_with_data) if c["symbol"] == symbol),
            0
        )

        # RSI(14) -- must be > 30 (not still crashing)
        rsi_val = _compute_rsi(closes, period=14)
        if rsi_val is None:
            log.debug("  %s: RSI not computable, skipping", symbol)
            continue
        if rsi_val <= 30:
            log.debug("  %s: RSI %.1f <= 30, still falling, skipping", symbol, rsi_val)
            continue

        # Volume recovery ratio (last 12h vs prior 12h) -- must be > 1.3x
        vol_ratio = _compute_volume_recovery_ratio(volumes)
        if vol_ratio < 1.3:
            log.debug("  %s: vol ratio %.2f < 1.3x, no volume recovery", symbol, vol_ratio)
            continue

        # SMA(20) cross -- price must have crossed above 20-period SMA
        sma_20 = _compute_sma(closes, 20)
        sma_cross = _find_sma_cross_bars_ago(closes, sma_20)

        if sma_cross is None:
            log.debug("  %s: price below SMA(20), no cross, skipping", symbol)
            continue

        # sma_cross >= 0 means we found a recent cross N bars ago
        # sma_cross == -1 means above SMA but no recent cross in 24 bars
        # Both are acceptable (we want price above SMA)

        # -- Recovery signal confirmed! Generate pick --
        log.info("  SIGNAL: %s | 7d: %.2f%% | RSI: %.1f | Vol: %.2fx | SMA cross: %s bars ago",
                 symbol, perf_7d, rsi_val, vol_ratio,
                 str(sma_cross) if sma_cross >= 0 else "24+")

        # Confidence scoring (0.5 to 0.95 range):
        # - How oversold: deeper drawdown = more confidence (max 0.25)
        # - Volume increase: higher ratio = more confidence (max 0.25)
        # - RSI direction: closer to 40-50 sweet spot = more confidence (max 0.25)
        # - Base confidence: 0.20

        conf_oversold = min(0.25, abs(perf_7d) / 40.0 * 0.25)  # -40% = max
        conf_volume = min(0.25, (vol_ratio - 1.0) / 3.0 * 0.25)  # 4x = max
        # RSI sweet spot: 35-50 is ideal recovery zone
        if 35 <= rsi_val <= 50:
            conf_rsi = 0.25
        elif 30 < rsi_val < 35:
            conf_rsi = 0.15
        elif 50 < rsi_val <= 60:
            conf_rsi = 0.15
        else:
            conf_rsi = 0.05
        conf_base = 0.20

        confidence = round(min(0.95, conf_base + conf_oversold + conf_volume + conf_rsi), 3)

        # TP/SL
        entry = current_price
        tp = _smart_round(entry * 1.06)   # +6% mean-reversion target
        sl = _smart_round(entry * 0.975)  # -2.5% stop loss
        entry_r = _smart_round(entry)

        # R:R calculation
        risk = entry - sl
        reward = tp - entry
        rr = round(reward / risk, 2) if risk > 0 else 2.4

        # Dedup check
        pick_id = f"relative_strength_recovery::{symbol}::{now_str}"
        if pick_id in existing_ids:
            log.info("  Skipping duplicate: %s", pick_id)
            continue

        # SMA(50) -- additional context for the pick
        sma_50 = _compute_sma(closes, 50)
        price_vs_sma50 = round(((current_price / sma_50[-1]) - 1) * 100, 2) if sma_50[-1] > 0 else None

        pick = {
            # Standard active_picks.json fields
            "id": pick_id,
            "strategy": "relative_strength_recovery",
            "symbol": symbol,
            "category": "crypto",
            "signal_type": "BUY",
            "entry_price": entry_r,
            "entry_date": now_str,
            "take_profit": tp,
            "stop_loss": sl,
            "confidence": confidence,
            "ml_score": None,
            "exit_price": None,
            "exit_date": None,
            "exit_reason": None,
            "pnl_pct": None,
            "pnl_dollar": None,
            "high_water_mark": None,
            "status": "OPEN",
            "regime_at_entry": None,
            "atr_at_entry": None,
            "rsi_at_entry": round(rsi_val, 1),
            "volume_ratio": round(vol_ratio, 3),
            "hold_days": None,
            "allocation": 1500.0,
            "gross_tp": tp,
            "net_tp": _smart_round(tp * (1 - 0.001)),  # 0.1% trading fee
            "transaction_cost_pct": 0.001,
            "cost_model": 0.001,
            "position_sizing": "risk_based",
            "risk_per_trade_pct": 0.02,
            "regime_compatible": True,
            "regime_adx": None,
            "regime_volatility": None,
            "regime_trend_direction": None,
            "regime_warning": None,
            "hmm_regime": None,
            "hmm_confidence": None,
            "hmm_signal": None,
            "hmm_leverage": None,
            "forward_trades": 2,
            "forward_wr": 1.0,
            "forward_validated": True,
            "rr": rr,
            # Strategy-specific extra fields
            "rank_7d": rank_7d,
            "total_pairs_ranked": len(candidates_with_data),
            "perf_7d_pct": round(perf_7d, 2),
            "volume_recovery_ratio": round(vol_ratio, 3),
            "sma_cross_bars_ago": sma_cross if sma_cross >= 0 else None,
            "price_vs_sma50_pct": price_vs_sma50,
            "scan_timestamp": now_iso,
        }
        picks.append(pick)

    # Sort by confidence descending (best recovery setups first)
    picks.sort(key=lambda p: p["confidence"], reverse=True)

    log.info("Found %d recovery signals from %d bottom-20%% candidates",
             len(picks), len(bottom_20pct))
    return picks


