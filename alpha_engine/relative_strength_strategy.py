def main():
    """Run the relative strength recovery scan."""
    log.info("=" * 60)
    log.info("RELATIVE STRENGTH RECOVERY SCANNER")
    log.info("Finding beaten-down coins showing early recovery signals")
    log.info("Criteria: bottom 20%% 7d perf + RSI>30 + vol surge + SMA cross")
    log.info("=" * 60)

    # 1. Scan
    picks = scan_relative_strength()

    if not picks:
        log.info("No recovery signals found. Market may not have beaten-down coins recovering yet.")
        _save_picks([])
        return

    # 2. Save results
    _save_picks(picks)
    _append_to_history(picks)

    # 3. Merge into active picks pipeline
    added = merge_into_active_picks(picks)

    # 4. Print summary
    log.info("")
    log.info("=" * 60)
    log.info("SCAN RESULTS")
    log.info("=" * 60)
    for p in picks:
        log.info(
            "  %s | 7d: %+.1f%% (rank %d/%d) | RSI: %.1f | Vol: %.2fx | Conf: %.0f%% | "
            "Entry $%.4f | TP $%.4f (+6%%) | SL $%.4f (-2.5%%) | R:R %.1f",
            p["symbol"], p["perf_7d_pct"], p["rank_7d"], p["total_pairs_ranked"],
            p["rsi_at_entry"], p["volume_recovery_ratio"], p["confidence"] * 100,
            p["entry_price"], p["take_profit"], p["stop_loss"], p["rr"],
        )
    log.info("")
    log.info("Total signals: %d | Merged to active: %d", len(picks), added)


if __name__ == "__main__":
    main()
