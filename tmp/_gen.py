L('"""')
L('Market Regime Detector -- HMM-Based Adaptive Model Selection')
L('=' * 61)
L('Detects 3 market regimes using Gaussian Hidden Markov Model:')
L('  - Bull   (trending up, expanding)')
L('  - Bear   (trending down, contracting/panic)')
L('  - Sideways (range-bound, low conviction)')
L('')
L('Outputs transition probability matrix, regime persistence')
L('probabilities, and per-regime TP/SL + position-size recs.')
L('')
L('Falls back to KMeans (4 clusters) if hmmlearn is unavailable.')
L('"""')
L('')
L('import json')
L('import numpy as np')
L('import pandas as pd')
L('from pathlib import Path')
L('from typing import Dict, Optional, Tuple')
