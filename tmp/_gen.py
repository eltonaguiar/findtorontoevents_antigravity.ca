L('except ImportError:')
L('    HMM_AVAILABLE = False')
L('')
L('')

L('class RegimeDetector:')
L('    """')
L('    Adaptive market regime detection.')
L('')
L('    Primary:  GaussianHMM with 3 hidden states (Bull / Bear / Sideways).')
L('    Fallback: KMeans with 4 clusters (original behaviour) when hmmlearn')
L('              is not installed.')
L('')
L('    Features (unchanged from v1):')
L('      - 20-day return  (trend direction)')
L('      - 20-day realised volatility  (calm vs wild)')
L('      - RSI-14  (momentum state)')
L('      - ADX-14  (trend strength)')
L('    """')
L('')
L('    BULL     = "bull"')
L('    BEAR     = "bear"')
L('    SIDEWAYS = "sideways"')
L('')
L('    N_HMM_STATES = 3')
L('')
L('    def __init__(self):')
