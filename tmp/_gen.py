L('        self._state_label_map: Dict[int, str] = {}')
L('        self._load_model()')
L('')

L('    def _load_model(self):')
L('        """Load saved regime model if it exists."""')
L('        model_path = MODELS_DIR / "regime_detector.joblib"')
L('        scaler_path = MODELS_DIR / "regime_scaler.joblib"')
L('        map_path = MODELS_DIR / "regime_state_map.json"')
L('')
L('        if model_path.exists() and scaler_path.exists():')
L('            try:')
L('                self.model = joblib.load(str(model_path))')
L('                self.scaler = joblib.load(str(scaler_path))')
L('                self.use_hmm = hasattr(self.model, "transmat_")')
L('                if map_path.exists():')
L('                    with open(map_path) as f:')
L('                        raw = json.load(f)')
L('                    self._state_label_map = {int(k): v for k, v in raw.items()}')
L('                backend = "HMM" if self.use_hmm else "KMeans"')
L('                print(f"[RegimeDetector] Loaded saved model ({backend})")')
L('            except Exception as exc:')
L('                print(f"[RegimeDetector] Failed to load model: {exc}")')
L('                self.model = None')
L('')
L('    def _save_model(self):')
L('        """Persist trained model + scaler + state-label mapping."""')
L('        MODELS_DIR.mkdir(parents=True, exist_ok=True)')
L('        joblib.dump(self.model, str(MODELS_DIR / "regime_detector.joblib"))')
L('        joblib.dump(self.scaler, str(MODELS_DIR / "regime_scaler.joblib"))')
L('        if self._state_label_map:')
L('            with open(MODELS_DIR / "regime_state_map.json", "w") as f:')
L('                json.dump(self._state_label_map, f)')
