L('    def _compute_features(self, df: pd.DataFrame) -> pd.DataFrame:')
L('        """')
L('        Compute regime classification features from OHLCV data.')
L('')
L('        Returns DataFrame with columns: [return_20d, volatility_20d, rsi_14, adx_14]')
L('        """')
L('        close = df["close"]')
L('        high = df["high"]')
L('        low = df["low"]')
L('')
L('        features = pd.DataFrame(index=df.index)')
L('')
L('        # 1. Trend: 20-day return')
L('        features["return_20d"] = close.pct_change(20) * 100')
L('')
L('        # 2. Volatility: 20-day realised vol (annualised)')
L('        log_returns = np.log(close / close.shift(1))')
L('        features["volatility_20d"] = log_returns.rolling(20).std() * np.sqrt(252) * 100')
L('')
L('        # 3. RSI-14')
L('        delta = close.diff()')
L('        gain = delta.clip(lower=0)')
L('        loss = (-delta).clip(lower=0)')
L('        avg_gain = gain.ewm(alpha=1 / 14, min_periods=14).mean()')
L('        avg_loss = loss.ewm(alpha=1 / 14, min_periods=14).mean()')
L('        rs = avg_gain / (avg_loss + 1e-10)')
L('        features["rsi_14"] = 100 - (100 / (1 + rs))')
L('')
L('        # 4. ADX-14')
L('        up_move = high.diff()')
L('        down_move = -low.diff()')
L('        plus_dm = pd.Series(')
L('            np.where((up_move > down_move) & (up_move > 0), up_move, 0),')
L('            index=high.index,')
L('        )')
L('        minus_dm = pd.Series(')
L('            np.where((down_move > up_move) & (down_move > 0), down_move, 0),')
L('            index=high.index,')
L('        )')
L('        tr = pd.concat(')
L('            [high - low, (high - close.shift(1)).abs(), (low - close.shift(1)).abs()],')
L('            axis=1,')
L('        ).max(axis=1)')
L('        atr_14 = tr.rolling(14).mean()')
L('        plus_di = 100 * plus_dm.ewm(span=14).mean() / (atr_14 + 1e-10)')
L('        minus_di = 100 * minus_dm.ewm(span=14).mean() / (atr_14 + 1e-10)')
L('        dx = 100 * (plus_di - minus_di).abs() / (plus_di + minus_di + 1e-10)')
L('        features["adx_14"] = dx.ewm(span=14).mean()')
L('')
L('        return features.dropna()')
L('')

L('    def train(self, btc_df: pd.DataFrame):')
L('        """')
L('        Train regime detector on BTC data (BTC drives overall market regime).')
L('')
L('        Uses GaussianHMM when hmmlearn is available, else KMeans.')
