L('')
L('        if len(features) < 100:')
L('            print("[RegimeDetector] Insufficient data for training")')
L('            return')
L('')
L('        X = features.values')
L('        X_scaled = self.scaler.fit_transform(X)')
L('')
L('        if self.use_hmm:')
L('            self._train_hmm(X_scaled, features)')
L('        else:')
L('            self._train_kmeans(X_scaled, features)')
L('')
L('        self._save_model()')
L('')
